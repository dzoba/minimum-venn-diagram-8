#!/usr/bin/env python3
"""Generate Venn37/Cert.lean from the certificate JSON (faces only; the JSON's separate edge list is not used).
Usage: gen_cert.py path/to/venn8_37_halfturn_a.json"""
import hashlib
import json
import pathlib
import sys

src = pathlib.Path(sys.argv[1])
raw = src.read_bytes()
sha = hashlib.sha256(raw).hexdigest()
assert sha == '7c1fed92b696db20c8b5eb44fe4d3e03b098fcf0d12fa6b499c040108c41dd12', sha
d = json.loads(raw)
assert d['n'] == 8
faces = [f['vertices'] for f in d['faces']]
lines = ',\n  '.join('[' + ', '.join(map(str, f)) + ']' for f in faces)
out = f"""/-
  The 37-face certificate venn8_37_halfturn_a.json (sha256 {sha}), faces only, generated by gen_cert.py.
-/
import Venn37.Defs

namespace Venn8

/-- The face list of the 37-crossing 8-Venn certificate, in the file's order and orientation. -/
def cert : List Face := [
  {lines}]

end Venn8
"""
pathlib.Path(__file__).resolve().parent.joinpath('Venn37', 'Cert.lean').write_text(out)
print('faces', len(faces), 'darts', sum(map(len, faces)), 'sha', sha)
